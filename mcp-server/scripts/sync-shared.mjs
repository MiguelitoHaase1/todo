#!/usr/bin/env node
// Copies canonical CLI source files into mcp-server/src/_shared/, applying
// two transforms so the synced copies are safe to run in a serverless function:
//
//   1. Replaces every `process.exit(N)` call with `throw new Error(...)` so a
//      missing env var or bad ID doesn't crash the Vercel worker.
//   2. Rewrites `from "../<name>.ts"` to `from "./<name>.ts"` so the flat
//      _shared/ tree resolves correctly.
//
// Idempotent — running twice produces byte-identical output. Run before tsc
// and before vercel dev/deploy. Configured as `vercel-build` in package.json
// so Vercel runs it automatically on deploy.

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, unlinkSync } from "node:fs";
import { dirname, resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, "../..");
const MCP_ROOT = resolve(__dirname, "..");
const SHARED_DIR = join(MCP_ROOT, "src/_shared");

// Manifest: source path (relative to repo root) → target filename in _shared/
const MANIFEST = [
  { src: "src/supabase.ts",         dest: "supabase.ts" },
  { src: "src/format.ts",           dest: "format.ts" },
  { src: "src/deferral.ts",         dest: "deferral.ts" },
  { src: "src/batch.ts",            dest: "batch.ts" },
  { src: "src/commands/triage.ts",  dest: "triage.ts" },
];

function rewriteProcessExit(source) {
  // Match `process.exit(N)` (with any single-digit code) and replace with a
  // throw. We pair it with the immediately preceding `console.error("...")`
  // to capture the message — the existing CLI uses this idiom consistently.
  // If no preceding console.error is found we fall back to a generic message.
  let count = 0;
  let out = source;

  // Pattern: console.error("msg"); ... process.exit(N);
  // We allow whitespace and other lines between (the existing code has loops
  // that print multiple errors before exiting).
  const exitRe = /process\.exit\(\d+\);/g;
  out = out.replace(exitRe, () => {
    count++;
    return 'throw new Error("operation aborted by guard (was process.exit)");';
  });

  return { source: out, count };
}

function rewriteImports(source) {
  // Two transforms applied to every relative import inside the synced files:
  //   1. Flatten "../<name>.ts" → "./<name>.ts" (the _shared/ tree is flat).
  //   2. Rewrite ".ts" extension → ".js" so Vercel's Node runtime can resolve
  //      the compiled output (Vercel emits .js but does not rewrite import
  //      paths). TypeScript with `moduleResolution: bundler` is happy with
  //      .js extensions even when the source is .ts.
  let count = 0;
  let out = source;

  // Step 1: parent → sibling
  out = out.replace(
    /from\s+(["'])\.\.\/([^"'\/]+\.ts)\1/g,
    (_match, quote, name) => {
      count++;
      return `from ${quote}./${name}${quote}`;
    },
  );

  // Step 2: .ts → .js for any remaining sibling import (covers both files
  // that originally had ../path.ts AND files that had ./path.ts).
  out = out.replace(
    /from\s+(["'])(\.\/?[^"']+)\.ts\1/g,
    (_match, quote, base) => {
      count++;
      return `from ${quote}${base}.js${quote}`;
    },
  );

  return { source: out, count };
}

function syncOne({ src, dest }) {
  const srcPath = join(REPO_ROOT, src);
  const destPath = join(SHARED_DIR, dest);

  if (!existsSync(srcPath)) {
    return null; // signal: skipped (upstream not present, e.g. Vercel build)
  }

  let contents = readFileSync(srcPath, "utf8");

  const exitResult = rewriteProcessExit(contents);
  contents = exitResult.source;

  const importResult = rewriteImports(contents);
  contents = importResult.source;

  const header =
    `// AUTO-GENERATED by mcp-server/scripts/sync-shared.mjs\n` +
    `// Source: ${src}\n` +
    `// DO NOT EDIT — run \`npm run sync-shared\` to regenerate.\n\n`;

  writeFileSync(destPath, header + contents);

  return {
    src,
    dest,
    bytes: contents.length,
    exitsRewritten: exitResult.count,
    importsRewritten: importResult.count,
  };
}

function clean() {
  if (!existsSync(SHARED_DIR)) return;
  for (const f of readdirSync(SHARED_DIR)) {
    if (f.endsWith(".ts")) unlinkSync(join(SHARED_DIR, f));
  }
}

function upstreamPresent() {
  // Detect whether the upstream src/ tree is available. On Vercel, only
  // mcp-server/ is uploaded, so REPO_ROOT/src does not exist — in that case
  // we trust that the synced _shared/ files are already in place from the
  // pre-deploy sync run on the developer's machine.
  return MANIFEST.every((entry) => existsSync(join(REPO_ROOT, entry.src)));
}

function main() {
  if (!existsSync(SHARED_DIR)) {
    mkdirSync(SHARED_DIR, { recursive: true });
  }

  if (!upstreamPresent()) {
    const existing = readdirSync(SHARED_DIR).filter((f) => f.endsWith(".ts"));
    console.log(`[sync-shared] upstream src/ not found (e.g. Vercel build env) — skipping sync`);
    console.log(`[sync-shared] using ${existing.length} pre-synced files in src/_shared/: ${existing.join(", ")}`);
    if (existing.length === 0) {
      throw new Error("[sync-shared] no pre-synced files in _shared/ AND no upstream available — cannot proceed");
    }
    return;
  }

  clean();

  console.log("[sync-shared] syncing CLI source into mcp-server/src/_shared/");
  let totalExits = 0;
  let totalImports = 0;

  for (const entry of MANIFEST) {
    const result = syncOne(entry);
    if (!result) continue;
    totalExits += result.exitsRewritten;
    totalImports += result.importsRewritten;
    console.log(
      `  ✓ ${result.src.padEnd(28)} → _shared/${result.dest.padEnd(15)}` +
      ` (${result.bytes} bytes, ${result.exitsRewritten} exit→throw, ${result.importsRewritten} import rewrites)`,
    );
  }

  console.log(`[sync-shared] done — ${MANIFEST.length} files, ${totalExits} exit→throw rewrites, ${totalImports} import rewrites`);
}

main();
